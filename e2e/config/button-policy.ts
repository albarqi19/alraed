/* ══════════════════════════════════════════════════════════════
   القرار
   ══════════════════════════════════════════════════════════════ */

export interface ButtonVerdict {
  safe: boolean
  /** سبب المنع — يظهر في التقرير كي يعرف القارئ لماذا لم يُجرَّب الزر */
  reason: string
}

/**
 * الحكم على زرٍّ من نصّه ومحدّداته.
 * تُستدعى بعد أن يكون المتصفّح قد فحص المحدّدات (نمرّرها كنتائجَ لا كعناصر).
 */
export function judgeButton(input: {
  label: string
  matchedForbiddenSelector: string | null
  matchedSafeSelector: string | null
  insideForm: boolean
}): ButtonVerdict {
  const label = input.label.trim()

  if (input.matchedForbiddenSelector) {
    return { safe: false, reason: `محدّد ممنوع: ${input.matchedForbiddenSelector}` }
  }

  if (!label) {
    // زرٌّ بأيقونةٍ بلا نصّ ولا aria-label: لا نعرف ماذا يفعل — فلا نضغطه.
    return { safe: false, reason: 'زرٌّ بلا نصّ ولا تسمية — نيّته مجهولة فالمنع أسلم' }
  }

  const lower = label.toLowerCase()
  const hit = forbiddenLabelWords.find((word) => lower.includes(word.toLowerCase()))
  if (hit) {
    return { safe: false, reason: `كلمةٌ ممنوعة في النصّ: «${hit}»` }
  }

  if (input.insideForm && !input.matchedSafeSelector) {
    return { safe: false, reason: 'زرٌّ داخل نموذج — قد يرسله' }
  }

  if (input.matchedSafeSelector) {
    return { safe: true, reason: `محدّد آمن: ${input.matchedSafeSelector}` }
  }

  if (safeLabelPatterns.some((pattern) => pattern.test(label))) {
    return { safe: true, reason: 'نصٌّ في قائمة السماح' }
  }

  return { safe: false, reason: 'لم يثبت أمانه — والافتراض هو المنع' }
}
